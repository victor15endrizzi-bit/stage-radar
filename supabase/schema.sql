-- ============================================================================
-- Radar de stages — schéma de la base (Supabase / Postgres)
-- À coller UNE FOIS dans Supabase > SQL Editor > New query > Run.
-- ============================================================================

create table if not exists settings (
  key        text primary key,
  value      jsonb,
  updated_at timestamptz default now()
);

create table if not exists sources (
  id                   text primary key,
  name                 text not null,
  kind                 text not null,          -- moovijob | workday | links | email
  config               jsonb not null default '{}',
  enabled              boolean not null default true,
  interval_minutes     int not null default 30,
  target               boolean not null default false,
  last_run_at          timestamptz,
  last_success_at      timestamptz,
  last_status          text,
  last_error           text,
  last_found           int default 0,
  consecutive_failures int default 0,
  alerted_failure      boolean default false,
  created_at           timestamptz default now()
);

create table if not exists jobs (
  id                    bigint generated by default as identity primary key,
  dedup_key             text unique not null,
  title                 text not null,
  company               text,
  company_norm          text,
  location              text,
  contract              text,
  description           text,
  url                   text not null,          -- lien direct vers l'annonce originale
  published_at          timestamptz,            -- date de publication (si connue)
  published_is_estimate boolean default false,
  detected_at           timestamptz default now(),
  is_internship         boolean,
  duration              text,
  start_date            text,
  languages             text[],
  domain                text,
  domain_label          text,
  score                 int,
  priority              text,                   -- prioritaire | interessante | faible | hors_stage
  analysis              jsonb,                  -- détail du score, missions, prérequis
  first_source_id       text,
  initial_import        boolean default false,  -- déjà en ligne avant l'activation du radar
  active                boolean default true,   -- false = annonce expirée / retirée
  expired_at            timestamptz,
  notified_at           timestamptz,
  digest_sent_at        timestamptz,
  -- suivi de candidature
  status                text default 'nouvelle',
  status_changed_at     timestamptz default now(),
  favorite              boolean default false,
  feedback              text,                   -- like | top | dislike
  notes                 text,
  applied_at            timestamptz,
  answered_at           timestamptz,
  next_action           text,
  next_action_at        timestamptz,
  manual                boolean default false,
  updated_at            timestamptz default now()
);
create index if not exists jobs_company_norm on jobs(company_norm);
create index if not exists jobs_detected on jobs(detected_at desc);
create index if not exists jobs_pending on jobs(notified_at, digest_sent_at) where active;

create table if not exists job_links (
  id             bigint generated by default as identity primary key,
  job_id         bigint references jobs(id) on delete cascade,  -- null = annonce ignorée (hors zone)
  source_id      text references sources(id) on delete cascade,
  external_id    text not null,
  url            text not null,
  first_seen_at  timestamptz default now(),
  last_seen_at   timestamptz default now(),
  missing_runs   int default 0,
  active         boolean default true,
  ignored_reason text,
  unique (source_id, external_id)
);
create index if not exists job_links_job on job_links(job_id);

create table if not exists status_history (
  id         bigint generated by default as identity primary key,
  job_id     bigint references jobs(id) on delete cascade,
  status     text not null,
  changed_at timestamptz default now()
);

create table if not exists source_runs (
  id          bigint generated by default as identity primary key,
  source_id   text references sources(id) on delete cascade,
  started_at  timestamptz,
  finished_at timestamptz,
  ok          boolean,
  found       int,
  new_jobs    int,
  error       text,
  initial     boolean default false
);
create index if not exists source_runs_started on source_runs(started_at desc);

create table if not exists reminders (           -- réservé (V2 : rappels multiples par offre)
  id      bigint generated by default as identity primary key,
  job_id  bigint references jobs(id) on delete cascade,
  due_at  timestamptz,
  label   text,
  done    boolean default false
);

-- ---------------------------------------------------------------------------
-- Historique automatique des statuts (pour les statistiques)
-- ---------------------------------------------------------------------------
create or replace function track_status() returns trigger language plpgsql as $$
begin
  if tg_op = 'INSERT' or new.status is distinct from old.status then
    new.status_changed_at := now();
    if new.status = 'envoyee' and new.applied_at is null then
      new.applied_at := now();
      -- relance proposée automatiquement 10 jours après l'envoi
      if new.next_action_at is null then
        new.next_action := 'Relancer';
        new.next_action_at := now() + interval '10 days';
      end if;
    end if;
    if new.status in ('entretien','offre','refus') and new.answered_at is null and new.applied_at is not null then
      new.answered_at := now();
    end if;
  end if;
  new.updated_at := now();
  return new;
end $$;

drop trigger if exists jobs_status on jobs;
create trigger jobs_status before insert or update on jobs
  for each row execute function track_status();

create or replace function log_status() returns trigger language plpgsql as $$
begin
  if tg_op = 'INSERT' or new.status is distinct from old.status then
    insert into status_history(job_id, status, changed_at) values (new.id, new.status, now());
  end if;
  return null;
end $$;

drop trigger if exists jobs_status_log on jobs;
create trigger jobs_status_log after insert or update on jobs
  for each row execute function log_status();

-- Nettoyage : on garde 60 jours d'historique d'exécution
create or replace function prune_runs() returns trigger language plpgsql as $$
begin
  delete from source_runs where started_at < now() - interval '60 days';
  return null;
end $$;
drop trigger if exists source_runs_prune on source_runs;
create trigger source_runs_prune after insert on source_runs
  for each statement execute function prune_runs();

