-- ---------------------------------------------------------------------------
-- Sécurité : seules les personnes connectées (toi) lisent/écrivent.
-- Le robot (GitHub Actions) utilise la clé service_role, qui contourne ces règles.
-- Pense à désactiver les inscriptions : Authentication > Sign In / Providers > "Allow new users to sign up" = OFF
-- ---------------------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array['settings','sources','jobs','job_links','status_history','source_runs','reminders'] loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists owner_all on %I', t);
    execute format('create policy owner_all on %I for all to authenticated using (true) with check (true)', t);
  end loop;
end $$;
